#!/usr/bin/env node
/* tools/robroy-manifest.js - writes the file list of app/assets/tr909-robroy/ into app/engine/sampled909.js
 * (between "// ---- MANIFEST" and "// ---- END MANIFEST"), so a missing or misnamed file is found by
 * tools/sampled909-check.js and not at play time. It only lists the folder: nothing in it is opened, changed or added.
 *
 *   node tools/robroy-manifest.js           rewrite the manifest block (exit 0)
 *   node tools/robroy-manifest.js --check   exit 1 if the block differs from the folder (prints the difference)
 */
'use strict';
var fs = require('fs'), path = require('path');

var ROOT = path.join(__dirname, '..');
var DIR = path.join(ROOT, 'app', 'assets', 'tr909-robroy');
var MOD = path.join(ROOT, 'app', 'engine', 'sampled909.js');
var BEGIN = '  // ---- MANIFEST (generated by tools/robroy-manifest.js from app/assets/tr909-robroy/; do not edit by hand)\n';
var END = '  // ---- END MANIFEST\n';

function listFolder() {
  if (!fs.existsSync(DIR)) return [];
  return fs.readdirSync(DIR).filter(function (f) { return fs.statSync(path.join(DIR, f)).isFile(); }).sort();
}
function block(files) {
  var lines = [], row = [];
  files.forEach(function (f) {
    row.push("'" + f.replace(/'/g, "\\'") + "'");
    if (row.length === 8) { lines.push('    ' + row.join(', ')); row = []; }
  });
  if (row.length) lines.push('    ' + row.join(', '));
  return BEGIN + '  var MANIFEST = [\n' + lines.join(',\n') + '\n  ];\n' + END;
}
function current(src) {
  var a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a < 0 || b < a) return null;
  return { a: a, b: b + END.length, text: src.slice(a, b + END.length) };
}

var files = listFolder(), src = fs.readFileSync(MOD, 'utf8'), cur = current(src), want = block(files);
if (!cur) { console.log('FAIL: no manifest block in ' + path.relative(ROOT, MOD)); process.exit(1); }
if (process.argv.indexOf('--check') >= 0) {
  if (cur.text === want) { console.log('OK: manifest matches the folder (' + files.length + ' files)'); process.exit(0); }
  var listed = (cur.text.match(/'[^']+'/g) || []).map(function (s) { return s.slice(1, -1); });
  files.forEach(function (f) { if (listed.indexOf(f) < 0) console.log('  in the folder, not in the manifest: ' + f); });
  listed.forEach(function (f) { if (files.indexOf(f) < 0) console.log('  in the manifest, not in the folder: ' + f); });
  console.log('FAIL: manifest differs from the folder; run node tools/robroy-manifest.js');
  process.exit(1);
}
if (cur.text !== want) fs.writeFileSync(MOD, src.slice(0, cur.a) + want + src.slice(cur.b));
console.log('manifest: ' + files.length + ' files' + (cur.text === want ? ' (unchanged)' : ' (written)'));
