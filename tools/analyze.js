#!/usr/bin/env node
/* tools/analyze.js (L2, Lab Crew): the element classifier from the command line.
 *
 *   node tools/analyze.js <file.wav> [more.wav ...] [--role drums|bass|other|vocals|auto] [--json <out.json>]
 *       Reports each file (a solo or a stem) as a readable table and, with --json, as JSON. Without --role the role is
 *       taken from the file name (drums, bass, other, vocals) or 'auto'. A drums stem is split into three bands.
 *   node tools/analyze.js --score <set> [--dir tools/out/analysis-truth]
 *       Scores the decisions against the labels of a truth set made by tools/analysis-truth.js (identity, reverb,
 *       poly, fm, drums). Exit 1 if the set's pass line fails (see SCORE below).
 *   node tools/analyze.js --build-drumlib [--dir tools/out/analysis-truth/drums]
 *       Writes app/analysis/drumlib.js (the Drums library for decision E) from the drums truth set.
 * Reads 16-bit, 24-bit and float32 WAV. Exit 0 on success, 1 on a failed score, 2 on bad input.
 */
'use strict';
var fs = require('fs'), path = require('path'), vm = require('vm');
var REPO = path.resolve(__dirname, '..'), AN = path.join(REPO, 'app', 'analysis');
['dsp.js', 'features.js', 'decide.js', 'drumlib.js', 'report.js'].forEach(function (f) {
  var p = path.join(AN, f);
  if (fs.existsSync(p)) vm.runInThisContext(fs.readFileSync(p, 'utf8'), { filename: p });
});
var A = globalThis.Analysis, F = A.features, X = A.decide;

function readWav(p) {
  var b = fs.readFileSync(p), off = 12, fmt = null, data = null;
  if (b.toString('ascii', 0, 4) !== 'RIFF' || b.toString('ascii', 8, 12) !== 'WAVE') throw new Error(p + ': not a WAV file');
  while (off < b.length - 8) { var id = b.toString('ascii', off, off + 4), sz = b.readUInt32LE(off + 4); if (id === 'fmt ') fmt = { tag: b.readUInt16LE(off + 8), ch: b.readUInt16LE(off + 10), sr: b.readUInt32LE(off + 12), bits: b.readUInt16LE(off + 22) }; else if (id === 'data') data = [off + 8, Math.min(sz, b.length - off - 8)]; off += 8 + sz + (sz & 1); }
  if (!fmt || !data) throw new Error(p + ': no fmt or data chunk');
  var bps = fmt.bits / 8, n = Math.floor(data[1] / bps / fmt.ch), L = new Float64Array(n), R = fmt.ch > 1 ? new Float64Array(n) : null, k, c;
  function rd(o) { if (fmt.bits === 16) return b.readInt16LE(o) / 32768; if (fmt.bits === 24) return b.readIntLE(o, 3) / 8388608; if (fmt.bits === 32 && fmt.tag === 3) return b.readFloatLE(o); if (fmt.bits === 32) return b.readInt32LE(o) / 2147483648; throw new Error(p + ': unsupported ' + fmt.bits + '-bit'); }
  for (k = 0; k < n; k++) { var o = data[0] + k * fmt.ch * bps; L[k] = rd(o); if (R) R[k] = rd(o + bps); }
  return { L: L, R: R, sr: fmt.sr };
}
function clean(o) { return JSON.parse(JSON.stringify(o, function (k, v) { if (k === '_tail' || k === 'frames') return undefined; if (typeof v === 'number' && v !== v) return null; return v; })); }

// ------------------------------------------------------------------ drum library
function buildDrumlib(dir) {
  var files = fs.readdirSync(dir).filter(function (f) { return /^dk-/.test(f) && f.endsWith('.wav') && !/^dk-smp-/.test(f); }).sort(), items = [];
  files.forEach(function (f) {
    var lab = JSON.parse(fs.readFileSync(path.join(dir, f.replace('.wav', '.json')), 'utf8')).labels, w = readWav(path.join(dir, f)), v = F.drumVector(w.L, w.R, w.sr);
    if (!v) return;
    items.push({ name: f.replace('.wav', ''), type: lab.type, machine: lab.machine || 'other', params: lab.params || {}, raw: F.DRUM_KEYS.map(function (k) { return v[k]; }) });
  });
  var K = F.DRUM_KEYS, mean = K.map(function (_, i) { var s = 0; items.forEach(function (it) { s += it.raw[i]; }); return s / items.length; });
  var sd = K.map(function (_, i) { var s = 0; items.forEach(function (it) { s += (it.raw[i] - mean[i]) * (it.raw[i] - mean[i]); }); return Math.sqrt(s / items.length) || 1; });
  items.forEach(function (it) { it.z = it.raw.map(function (x, i) { return Math.round(1000 * (x - mean[i]) / sd[i]) / 1000; }); delete it.raw; });
  var lib = { keys: K, mean: mean, sd: sd, items: items };
  var nn = items.map(function (it) { var best = Infinity; items.forEach(function (o) { if (o !== it) { var s = 0; for (var i = 0; i < K.length; i++) s += (it.z[i] - o.z[i]) * (it.z[i] - o.z[i]); best = Math.min(best, Math.sqrt(s / K.length)); } }); return best; });
  lib.nnMedian = A.dsp.median(nn);
  var txt = '/* Havantechno analysis - drumlib.js. GENERATED by `node tools/analyze.js --build-drumlib` from the drums truth set of\n' +
    ' * tools/analysis-truth.js (' + items.length + ' renders: the 27 Drums voices at their defaults and three random knob settings each,\n' +
    ' * and the engine\'s own synth drums as machine "other"). Do not edit by hand. Global Analysis.drumlib, used by decide.drumMachine.\n */\n' +
    '(function () {\n  var root = (typeof window !== \'undefined\') ? window : (typeof globalThis !== \'undefined\' ? globalThis : this);\n' +
    '  var A = root.Analysis = root.Analysis || {};\n  A.drumlib = ' + JSON.stringify(lib) + ';\n})();\n';
  fs.writeFileSync(path.join(AN, 'drumlib.js'), txt);
  console.log('drumlib.js: ' + items.length + ' items, ' + K.length + ' features, library nearest-neighbour median ' + lib.nnMedian.toFixed(3));
  return lib;
}

// ------------------------------------------------------------------ scoring against truth labels
function loadSet(dir) {
  return fs.readdirSync(dir).filter(function (f) { return f.endsWith('.wav'); }).sort().map(function (f) {
    return { name: f.replace('.wav', ''), file: path.join(dir, f), labels: JSON.parse(fs.readFileSync(path.join(dir, f.replace('.wav', '.json')), 'utf8')).labels };
  });
}
var SCORE = {
  identity: function (items) {
    var rows = [], wrong = 0;
    items.forEach(function (it) {
      var w = readWav(it.file), d = X.synthOrSample(F.identity(w.L, w.R, w.sr)), t = it.labels.source;
      // a confident wrong call is a failure; capped or undecided calls on deterministic synthesis are expected
      var bad = (d.value === 'sample' && t === 'synth' && d.confidence !== 'low') || (d.value === 'synth' && t === 'sample');
      if (bad) wrong++;
      rows.push([it.name, t, d.value, d.confidence, bad ? 'WRONG' : '']);
    });
    return { rows: rows, pass: wrong === 0, summary: wrong + ' confident wrong calls of ' + items.length };
  },
  reverb: function (items) {
    var rows = [], bad = 0;
    items.forEach(function (it) {
      var w = readWav(it.file), r = X.reverb(F.freeDecay(w.L, w.R, w.sr), F.predelay(w.L, w.R, w.sr)), t = it.labels.reverb || {};
      var ok = r.value.present === t.present, rtErr = t.rt60 && r.value.rt60 ? r.value.rt60 / t.rt60 - 1 : null;
      if (!ok && r.confidence !== 'low') bad++;
      rows.push([it.name, t.present + (t.rt60 ? ' ' + t.rt60 + ' s' : ''), r.value.present + (r.value.rt60 ? ' ' + r.value.rt60.toFixed(2) + ' s' : ''), r.confidence, rtErr == null ? '' : Math.round(100 * rtErr) + ' %', ok ? '' : 'WRONG']);
    });
    return { rows: rows, pass: bad === 0, summary: bad + ' confident wrong presence calls of ' + items.length };
  },
  poly: function (items) {
    var rows = [], ok = 0, exact = 0;
    items.forEach(function (it) {
      var w = readWav(it.file), p = F.polyphony(w.L, w.R, w.sr), d = X.monoPoly(p), t = it.labels.polyphony;
      var truth = it.labels.instrumentVoices === 1 || (t === 1 && !it.labels.line && it.labels.element !== 'pad') ? 'mono' : 'poly';
      if (it.labels.line && it.labels.instrumentVoices !== 1) truth = 'either';   // a poly synth playing a line
      var good = truth === 'either' || d.value === truth; if (good) ok++; if (p.median === t) exact++;
      rows.push([it.name, t + ' notes', truth, d.value, d.confidence, p.median, good ? '' : 'WRONG']);
    });
    return { rows: rows, pass: ok === items.length, summary: ok + ' of ' + items.length + ' mono/poly right; ' + exact + ' exact median counts' };
  },
  fm: function (items) {
    var rows = [], ok = 0, wrong = 0;
    items.forEach(function (it) {
      var w = readWav(it.file), fit = F.fmFit(w.L, w.R, w.sr), d = X.fmOrSubtractive(fit), t = it.labels.synthesis;
      if (d.value === t) ok++; else if (d.value === 'fm' || d.value === 'subtractive') wrong++;
      rows.push([it.name, t, d.value, d.confidence, fit.fm ? fit.fm.pair.join(':') + ' I ' + fit.fm.indexStart + '->' + fit.fm.indexEnd : '', d.value === t ? '' : (d.value === 'fm' || d.value === 'subtractive' ? 'WRONG' : 'no call')]);
    });
    return { rows: rows, pass: wrong === 0, summary: ok + ' of ' + items.length + ' right, ' + wrong + ' wrong' };
  },
  drums: function (items) {
    var lib = A.drumlib; if (!lib) throw new Error('no drumlib.js: run --build-drumlib first');
    var rows = [], mOk = 0, vOk = 0, n = 0, smpOk = 0, smpN = 0, hi = 0, hiOk = 0, oth = 0;
    items.forEach(function (it) {
      var w = readWav(it.file), id = X.synthOrSample(F.identity(w.L, w.R, w.sr)), vec = F.drumVector(w.L, w.R, w.sr);
      var isSmp = /^dk-smp-/.test(it.name), truthM = isSmp ? (it.labels.sampleOf.slice(-3) === '808' ? 'tr808' : 'tr909') : it.labels.machine || 'other';
      var truthV = isSmp ? it.labels.sampleOf : it.labels.type;
      // leave one out: the item itself is not in the library (a sampler replay's source render stays: it is another file).
      // The engine's synth drums ('other') have one render each, so leaving one out removes its class: reported apart.
      var d1 = X.drumMachine(vec, id, { exclude: function (x) { return x.name === it.name; } });
      if (truthM === 'other') { oth++; rows.push([it.name, 'other ' + truthV, d1.value.machine + ' ' + d1.value.voice, d1.confidence, '(class absent once left out)']); return; }
      n++; var ok = d1.value.machine === truthM; if (ok) mOk++; if (d1.value.voice === truthV) vOk++;
      if (d1.confidence === 'high') { hi++; if (ok) hiOk++; }
      if (isSmp) { smpN++; if (d1.value.source === 'sample') smpOk++; }
      rows.push([it.name, truthM + ' ' + truthV, d1.value.machine + ' ' + d1.value.voice + ' (' + d1.value.source + ')', d1.confidence, ok ? '' : 'WRONG']);
    });
    return { rows: rows, pass: mOk / n >= 0.8 && (hi === 0 || hiOk / hi >= 0.95), summary: 'machine right ' + mOk + ' of ' + n + ', voice right ' + vOk + ' of ' + n + ' (item left out); high-confidence calls right ' + hiOk + ' of ' + hi + '; sampler replays called sample ' + smpOk + ' of ' + smpN + '; ' + oth + ' engine synth drums not scored' };
  }
};

function main() {
  var a = process.argv.slice(2), role = null, jsonOut = null, files = [], dir = null, score = null, build = false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] === '--role') role = a[++i];
    else if (a[i] === '--json') jsonOut = a[++i];
    else if (a[i] === '--dir') dir = a[++i];
    else if (a[i] === '--score') score = a[++i];
    else if (a[i] === '--build-drumlib') build = true;
    else if (a[i].charAt(0) === '-') { console.error('analyze.js: unknown option ' + a[i]); process.exit(2); }
    else files.push(a[i]);
  }
  if (build) { buildDrumlib(dir || path.join(REPO, 'tools', 'out', 'analysis-truth', 'drums')); return 0; }
  if (score) {
    if (!SCORE[score]) { console.error('analyze.js: no scorer for ' + score); return 2; }
    var d = dir || path.join(REPO, 'tools', 'out', 'analysis-truth', score);
    if (!fs.existsSync(d)) { console.error('analyze.js: ' + d + ' missing; run node tools/analysis-truth.js --sets ' + score); return 2; }
    var r = SCORE[score](loadSet(d));
    r.rows.forEach(function (row) { console.log(row.join(' | ')); });
    console.log((r.pass ? 'PASS ' : 'FAIL ') + score + ': ' + r.summary);
    return r.pass ? 0 : 1;
  }
  if (!files.length) { console.error('usage: node tools/analyze.js <file.wav> [--role drums|bass|other|vocals|auto] [--json out]'); return 2; }
  var results = [];
  for (var f = 0; f < files.length; f++) {
    var w; try { w = readWav(files[f]); } catch (e) { console.error('analyze.js: ' + e.message); return 2; }
    var base = path.basename(files[f], '.wav'), rl = role || (/drums/.test(base) ? 'drums' : /bass/.test(base) ? 'bass' : /vocals/.test(base) ? 'vocals' : /other/.test(base) ? 'other' : 'auto');
    results.push(A.report.stem(w.L, w.R, w.sr, { name: base, role: rl }));
  }
  var all = []; results.forEach(function (r) { all = all.concat(r.elements); });
  var sh = A.report.shared(all);
  console.log(A.report.table(results));
  console.log('\nreverb groups (shared or element-specific): ' + JSON.stringify(sh.groups));
  all.forEach(function (e) {
    console.log('\n' + e.name + ': recreation ' + (e.recreation ? e.recreation.type + ' ' + JSON.stringify(e.recreation.params) + ' [' + e.recreation.confidence + '] - ' + e.recreation.why.join('; ') : 'none'));
    Object.keys(e.decisions).forEach(function (k) { console.log('  ' + k + ': ' + e.decisions[k].evidence.join('; ')); });
    if (e.unverified.length) console.log('  unverified: ' + e.unverified.join('; '));
  });
  if (jsonOut) { fs.writeFileSync(jsonOut, JSON.stringify(clean({ tool: 'tools/analyze.js', note: 'output of an unvalidated tool', results: results, reverbGroups: sh.groups }), null, 1)); console.log('\nJSON written to ' + jsonOut); }
  return 0;
}
process.exit(main());
